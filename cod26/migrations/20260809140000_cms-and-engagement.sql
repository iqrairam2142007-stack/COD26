-- ============================================ single source of truth for free
-- is_free_unit() used to hardcode "unit 1". It now reads public.units, so an
-- admin ticking "free" in the dashboard changes every gate at once - chapter
-- text, videos, resources and the quiz function.
--
-- The volatility changes (IMMUTABLE -> STABLE), so the function has to be
-- dropped and rebuilt; the policy that depends on it is rebuilt with it.
DROP POLICY IF EXISTS unit_videos_read ON public.unit_videos;
DROP FUNCTION IF EXISTS public.is_free_unit(INTEGER);

CREATE FUNCTION public.is_free_unit(p_unit_id INTEGER)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.units WHERE id = p_unit_id AND is_free
  );
$$;

CREATE POLICY unit_videos_read ON public.unit_videos
  FOR SELECT TO authenticated, anon
  USING (
    public.is_free_unit(unit_id)
    OR public.has_course_access()
    OR public.is_admin()
  );

-- Keep the videos table pointing at real units now that they exist.
ALTER TABLE public.unit_videos DROP CONSTRAINT IF EXISTS unit_videos_unit_id_check;
