-- Course content moves out of the frontend bundle and into the database, plus
-- the engagement features: resources, attendance, notifications.
--
-- Until now units and chapters lived in src/data/unitdata.js, so an admin
-- could not change a single word without a redeploy. They are tables now.

-- ==========================================================  units + chapters
CREATE TABLE IF NOT EXISTS public.units (
  id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title                    TEXT NOT NULL,
  difficulty               TEXT NOT NULL DEFAULT 'Beginner'
                             CHECK (difficulty IN ('Beginner', 'Intermediate', 'Advanced')),
  duration                 TEXT,
  position                 INTEGER NOT NULL DEFAULT 0,
  is_free                  BOOLEAN NOT NULL DEFAULT FALSE,
  is_published             BOOLEAN NOT NULL DEFAULT TRUE,
  assignment_title         TEXT,
  assignment_deadline_days INTEGER,
  assignment_points        INTEGER,
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at               TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS units_position_idx ON public.units (position, id);

CREATE TABLE IF NOT EXISTS public.chapters (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  unit_id    INTEGER NOT NULL REFERENCES public.units(id) ON DELETE CASCADE,
  position   INTEGER NOT NULL,
  title      TEXT NOT NULL,
  content    TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (unit_id, position)
);
CREATE INDEX IF NOT EXISTS chapters_unit_idx ON public.chapters (unit_id, position);

-- ================================================================= resources
-- Notes, PDFs, cheat sheets and external links attached to a unit.
CREATE TABLE IF NOT EXISTS public.resources (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  unit_id     INTEGER NOT NULL REFERENCES public.units(id) ON DELETE CASCADE,
  title       TEXT NOT NULL,
  description TEXT,
  kind        TEXT NOT NULL DEFAULT 'file' CHECK (kind IN ('file', 'link')),
  url         TEXT NOT NULL,
  storage_key TEXT,
  mime_type   TEXT,
  size_bytes  BIGINT,
  position    INTEGER NOT NULL DEFAULT 0,
  created_by  UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS resources_unit_idx ON public.resources (unit_id, position);

-- ================================================================ attendance
-- One row per student per day they actually studied. `day` is a date so the
-- primary key makes repeat visits idempotent.
CREATE TABLE IF NOT EXISTS public.attendance (
  user_id       UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  day           DATE NOT NULL DEFAULT CURRENT_DATE,
  first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  visits        INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (user_id, day)
);
CREATE INDEX IF NOT EXISTS attendance_day_idx ON public.attendance (day DESC);

-- Called by the app on load. SECURITY DEFINER so a student can only ever
-- stamp their own attendance, never anybody else's.
CREATE OR REPLACE FUNCTION public.mark_attendance()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF auth.uid() IS NULL THEN RETURN; END IF;
  INSERT INTO public.attendance (user_id, day)
  VALUES (auth.uid(), CURRENT_DATE)
  ON CONFLICT (user_id, day) DO UPDATE
    SET last_seen_at = now(),
        visits       = public.attendance.visits + 1;
END;
$$;

-- ============================================================= notifications
-- user_id NULL means "everyone" - one row instead of a fan-out per student.
CREATE TABLE IF NOT EXISTS public.notifications (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id    UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  title      TEXT NOT NULL,
  body       TEXT NOT NULL DEFAULT '',
  level      TEXT NOT NULL DEFAULT 'info' CHECK (level IN ('info', 'success', 'warning')),
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS notifications_feed_idx ON public.notifications (created_at DESC);
CREATE INDEX IF NOT EXISTS notifications_user_idx ON public.notifications (user_id, created_at DESC);

-- Read state is per user, so a broadcast can be read by one student and not
-- another without duplicating the message.
CREATE TABLE IF NOT EXISTS public.notification_reads (
  notification_id UUID NOT NULL REFERENCES public.notifications(id) ON DELETE CASCADE,
  user_id         UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  read_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (notification_id, user_id)
);

