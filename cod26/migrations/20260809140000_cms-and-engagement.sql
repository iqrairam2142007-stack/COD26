-- --------------------------------------------------------------------- units
-- Unit metadata (title, difficulty, whether it is free) is catalogue data:
-- the marketing pages show it to signed-out visitors. Chapter *content* is
-- what the paywall protects.
DROP POLICY IF EXISTS units_read ON public.units;
CREATE POLICY units_read ON public.units
  FOR SELECT TO anon, authenticated
  USING (is_published OR public.is_admin());

DROP POLICY IF EXISTS units_admin_write ON public.units;
CREATE POLICY units_admin_write ON public.units
  FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

-- ------------------------------------------------------------------ chapters
DROP POLICY IF EXISTS chapters_read ON public.chapters;
CREATE POLICY chapters_read ON public.chapters
  FOR SELECT TO anon, authenticated
  USING (
    public.is_admin()
    OR public.has_course_access()
    OR EXISTS (SELECT 1 FROM public.units u WHERE u.id = unit_id AND u.is_free)
  );

DROP POLICY IF EXISTS chapters_admin_write ON public.chapters;
CREATE POLICY chapters_admin_write ON public.chapters
  FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

-- ----------------------------------------------------------------- resources
DROP POLICY IF EXISTS resources_read ON public.resources;
CREATE POLICY resources_read ON public.resources
  FOR SELECT TO anon, authenticated
  USING (
    public.is_admin()
    OR public.has_course_access()
    OR EXISTS (SELECT 1 FROM public.units u WHERE u.id = unit_id AND u.is_free)
  );

DROP POLICY IF EXISTS resources_admin_write ON public.resources;
CREATE POLICY resources_admin_write ON public.resources
  FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

-- ---------------------------------------------------------------- attendance
DROP POLICY IF EXISTS attendance_own ON public.attendance;
CREATE POLICY attendance_own ON public.attendance
  FOR SELECT TO authenticated
  USING (user_id = auth.uid() OR public.is_admin());

-- ------------------------------------------------------------- notifications
DROP POLICY IF EXISTS notifications_read ON public.notifications;
CREATE POLICY notifications_read ON public.notifications
  FOR SELECT TO authenticated
  USING (user_id IS NULL OR user_id = auth.uid() OR public.is_admin());

DROP POLICY IF EXISTS notifications_admin_write ON public.notifications;
CREATE POLICY notifications_admin_write ON public.notifications
  FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS notification_reads_own ON public.notification_reads;
CREATE POLICY notification_reads_own ON public.notification_reads
  FOR ALL TO authenticated
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());

